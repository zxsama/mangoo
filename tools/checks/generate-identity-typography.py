"""Generate bounded offline identity outlines. Requires fonttools==4.60.1.

python tools/checks/generate-identity-typography.py --font <cached OTF> --output <directory>
Download source only into ignored scratch; no font is shipped with the app.
"""
import argparse
import hashlib
import json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

PIN = 'f8d157532fbfaeda587e826d4cd5b21a49186f7c'
SHA256 = 'ca094f6b0001fb048ca39ddd797a0cdb0179e1e55c6561e111c49c3e6a61d7b7'
URL = f'https://raw.githubusercontent.com/notofonts/noto-cjk/{PIN}/Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Medium.otf'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    assert hashlib.sha256(args.font.read_bytes()).hexdigest() == SHA256, 'Unexpected source font'
    font = TTFont(args.font)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    entries, paths, bounds = [], {}, {}
    english = 'zero one two three four five six seven eight nine ten eleven twelve'.split()
    chinese = list('零一二三四五六七八九十') + ['十一', '十二']
    romans = 'I II III IV V VI VII VIII IX X XI XII'.split()

    def add(key, char, label, category, keywords, square=False):
        glyph = glyphs[cmap[ord(char)]]
        pen = BoundsPen(glyphs)
        glyph.draw(pen)
        x0, y0, x1, y1 = pen.bounds
        cjk = category == 'chinese-numerals'
        scale = min((12 if square else 16) / 733, 20 / (x1-x0)) if not cjk else 18 / 1000
        tx = 12 - (x0+x1)*scale/2
        ty = 18 if not cjk else 12 + (y0+y1)*scale/2
        box = [tx+x0*scale, ty-y1*scale, tx+x1*scale, ty-y0*scale]
        assert min(box) >= 0 and max(box) <= 24, (key, box)
        out = SVGPathPen(glyphs, ntos=lambda n: f'{n:.3f}'.rstrip('0').rstrip('.'))
        glyph.draw(TransformPen(out, (scale, 0, 0, -scale, tx, ty)))
        shape = [{'d': out.getCommands()}]
        if square:
            shape.insert(0, {'d': 'M2 2H22V22H2ZM3.5 3.5V20.5H20.5V3.5Z', 'fillRule': 'evenodd'})
        paths[key] = shape
        bounds[key] = box
        entries.append(dict(key=key, label=label, category=category, source=f'NotoSansCJKsc-Medium U+{ord(char):04X}' + (' + generated square' if square else ''), sourceKind='typographic', keywords=f'{char} {keywords}'))

    for case, start in [('uppercase', 65), ('lowercase', 97)]:
        for value in range(26):
            char = chr(start+value)
            add(f'letter-{case}-{char.lower()}', char, f'{"大写" if case == "uppercase" else "小写"}字母 {char}', f'letters-{case}', f'letter alphabet latin {case} {char} 字母 拉丁 英文 {"大写" if case == "uppercase" else "小写"}')
    for square in [False, True]:
        for value in range(10):
            add(f'number-{"square" if square else "plain"}-{value}', str(value), f'{"方框" if square else "阿拉伯"}数字 {value}', 'numbers', f'number digit decimal arabic {"square 方框" if square else "plain 普通"} {value} {english[value]} {chinese[value]} 数字 编号 阿拉伯', square)
    for case, start in [('uppercase', 0x2160), ('lowercase', 0x2170)]:
        for index in range(12):
            roman = romans[index] if case == 'uppercase' else romans[index].lower()
            add(f'roman-{case}-{index+1}', chr(start+index), f'{"大写" if case == "uppercase" else "小写"}罗马数字 {roman}', f'roman-{case}', f'roman numeral {case} {roman} {index+1} {english[index+1]} {chinese[index+1]} 数字 罗马 {"大写" if case == "uppercase" else "小写"}')
    for char, value, kind in [('〇', 0, 'circle')] + [(c, i, 'ordinary') for i, c in enumerate('零一二三四五六七八九十')] + [(c, i+1, 'financial') for i,c in enumerate('壹贰叁肆伍陆柒捌玖拾')]:
        add(f'chinese-{kind}-{value}', char, f'{"财务" if kind == "financial" else "中文"}数字 {char}', 'chinese-numerals', f'chinese numeral {kind} {value} {english[value]} {chinese[value]} 中文 汉字 数字 {"financial 大写 财务 金额" if kind == "financial" else "小写 普通"}')
    header = f'/*! Derived from Noto Sans CJK SC Medium; © 2014-2021 Adobe. SIL OFL 1.1.\n * Full license ships at /LICENSE-NotoSansCJK.txt; see identityTypography.LICENSE.md.\n * Source commit {PIN}.\n * Generated by tools/checks/generate-identity-typography.py; do not edit. */\n'
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output/'identityTypographicPaths.ts').write_text(header + 'import type { IdentityPath } from "./identityFluentPaths";\nexport const IDENTITY_TYPOGRAPHIC_PATHS: Readonly<Record<string, readonly IdentityPath[]>> = ' + json.dumps(paths, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    (args.output/'identityTypographicCatalog.ts').write_text(header + 'import type { IdentityIconDescriptor } from "./identityCatalog";\nexport const IDENTITY_TYPOGRAPHIC_ICONS = ' + json.dumps(entries, ensure_ascii=False, indent=2) + ' as const satisfies readonly IdentityIconDescriptor[];\n', encoding='utf-8')
    (args.output/'typographic-bounds.json').write_text(json.dumps(bounds, indent=2), encoding='utf-8')
    print(f'{len(entries)} outlines generated from {URL}')

if __name__ == '__main__':
    main()
