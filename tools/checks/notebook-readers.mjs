function cjkPdf() {
  const stream = text => `<< /Length ${text.length} >>\nstream\n${text}\nendstream`;
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Count 2 /Kids [3 0 R 4 0 R] >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 180] /Contents 5 0 R /Resources << /Font << /F1 7 0 R >> >> >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 180] /Contents 6 0 R /Resources << /Font << /F1 9 0 R >> >> >>",
    stream("BT /F1 36 Tf 30 95 Td <D6D0CEC4> Tj ET"), // 中文 in GB-EUC-H
    stream("BT /F1 24 Tf 30 95 Td (Second PDF page) Tj ET"),
    "<< /Type /Font /Subtype /Type0 /BaseFont /STSong-Light /Encoding /GB-EUC-H /DescendantFonts [8 0 R] >>",
    "<< /Type /Font /Subtype /CIDFontType0 /BaseFont /STSong-Light /CIDSystemInfo << /Registry (Adobe) /Ordering (GB1) /Supplement 4 >> /FontDescriptor 10 0 R /DW 1000 >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    "<< /Type /FontDescriptor /FontName /STSong-Light /Flags 6 /FontBBox [-25 -254 1000 880] /ItalicAngle 0 /Ascent 880 /Descent -120 /CapHeight 880 /StemV 80 >>"
  ];
  let data = "%PDF-1.4\n";
  const offsets = [0];
  for (let i = 0; i < objects.length; i++) { offsets.push(data.length); data += `${i + 1} 0 obj\n${objects[i]}\nendobj\n`; }
  const xref = data.length;
  data += `xref\n0 ${offsets.length}\n0000000000 65535 f \n` + offsets.slice(1).map(n => `${String(n).padStart(10,"0")} 00000 n \n`).join("");
  data += `trailer\n<< /Size ${offsets.length} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(data);
}
samples.set("cjk.pdf", cjkPdf());
await writeFile(path.join(run,"cjk.pdf"), samples.get("cjk.pdf"));
function mount(server) {
  server.middlewares.use("/reader-fixtures", (req, res, next) => {
    const binary = samples.get(req.url.slice(1));
    if (!binary) return next();
    res.setHeader("Content-Type", "application/octet-stream"); res.end(binary);
  });
}
const input = path.join(root, "tests/fixtures/notebook-readers.html");
const common = { root, configFile: path.join(root, "vite.config.ts"), logLevel:"error", cacheDir: path.join(run, "vite"), optimizeDeps:{ entries:[input] },
  plugins: [{ name: "notebook-reader-fixtures", configureServer: mount }] };
const output = path.join(run, "web");
async function productionCore(port) {
  await build({ ...common, build:{ outDir:output, rollupOptions:{ input } } });
  await copyFile(path.join(output,"tests/fixtures/notebook-readers.html"),path.join(output,"index.html"));
  await mkdir(path.join(output,"reader-fixtures"));
  for (const [name, binary] of samples) await writeFile(path.join(output,"reader-fixtures",name),binary);
  const binary = resolveCoreBinary();
  const executable = path.join(run,path.basename(binary));
  await copyFile(binary,executable);
  const origin = "http://127.0.0.1:" + port;
  const core = spawn(executable,[],{ windowsHide:true, stdio:["ignore","pipe","pipe"], env:{
    ...process.env, ...managedLibraryHostEnv(run), MANGOO_WEB_DIR:output, MANGOO_SERVE_WEB:"1",
    MANGOO_CORE_ADDR:"127.0.0.1:"+port, MANGOO_ALLOWED_ORIGIN:origin, MANGOO_SESSION_TOKEN:randomBytes(32).toString("hex"),
    MANGOO_PARENT_PID:String(process.pid), PATH:path.dirname(binary)+path.delimiter+process.env.PATH
  } });
  let log = ""; core.stdout.on("data",chunk => log += chunk); core.stderr.on("data",chunk => log += chunk);
  const closed = new Promise(resolve => core.once("exit",resolve));
  const close = async () => { core.kill(); await closed; };
  try {
    for (let count = 0; count < 100; count++) {
      const ok = await fetch(origin+"/tests/fixtures/notebook-readers.html").then(response => response.ok).catch(() => false);
      if (ok) return { close };
      if (core.exitCode !== null) break;
      await delay(100);
    }
    throw new Error("Production Core did not serve the test bundle. " + log);
  } catch (error) { await close(); throw error; }
}
let failures = 0;
for (const mode of ["development","production"]) {
  const port = await availableLoopbackPort(0);
  const serverOptions = { host:"127.0.0.1", port, strictPort:true };
  let server;
  if (mode === "development") { server = await createServer({ ...common, server: serverOptions }); await server.listen(); }
  else server = await productionCore(port);
  try {
    const report = path.join(run,mode); await mkdir(report);
    const env = { ...process.env, NOTEBOOK_READER_REPORT: report }; delete env.ELECTRON_RUN_AS_NODE;
    const electron = (await import("electron")).default;
    const child = spawn(electron, [path.join(root,"tests/fixtures/runNotebookReaders.mjs"),
      `http://127.0.0.1:${port}/tests/fixtures/notebook-readers.html`], {env, windowsHide:true, stdio:["ignore","pipe","pipe"]});
    child.stdout.pipe(process.stdout); child.stderr.pipe(process.stderr);
    const code = await new Promise((resolve,reject) => { child.on("error",reject); child.on("exit",resolve); });
    if (code !== 0) { failures++; console.error(mode, "Electron exit", code); }
  } finally {
    await server.close();
  }
}
console.log("Reader verification artifacts", run);
process.exitCode = failures ? 1 : 0;
