import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const release = process.argv.includes("--release");
const profile = release ? "release" : "debug";
execFileSync("cargo", ["build", ...(release ? ["--release"] : []), "-p", "megle-fake-provider"], { cwd: root, stdio: "inherit", shell: process.platform === "win32" });
const binaryName = process.platform === "win32" ? "megle-fake-provider.exe" : "megle-fake-provider";
const targetRoot = process.env.CARGO_TARGET_DIR
  ? path.resolve(root, process.env.CARGO_TARGET_DIR)
  : path.join(root, "target");
const source = path.join(targetRoot, profile, binaryName);
const pluginRoot = path.join(targetRoot, profile, "bundled-plugins", "com.megle.fake-sync");
const binary = path.join(pluginRoot, "bin", binaryName);
mkdirSync(path.dirname(binary), { recursive: true });
copyFileSync(source, binary);
const sha256 = createHash("sha256").update(readFileSync(binary)).digest("hex");
const template = readFileSync(path.join(root, "bundled-plugins", "com.megle.fake-sync", "plugin.template.json"), "utf8");
writeFileSync(path.join(pluginRoot, "plugin.json"), template.replaceAll("__SHA256__", sha256));
const values = sha256.match(/../g).map(v => `0x${v}`);
const rows = [values.slice(0, 16), values.slice(16)].map(row => `    ${row.join(", ")},`).join("\n");
writeFileSync(path.join(root, "crates", "core", "src", "plugins", "runtime", "generated_trust.rs"), `// Generated by tools/build/build-bundled-plugins.mjs.\npub const GENERATED_FAKE_PROVIDER_SHA256: [u8; 32] = [\n${rows}\n];\n`);
console.log(`[bundled-plugin] ${pluginRoot} ${sha256}`);
