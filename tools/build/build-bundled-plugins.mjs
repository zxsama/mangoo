import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const release = process.argv.includes("--release");
if (release) {
  const bundledClientId = process.env.MEGLE_BUNDLED_ONEDRIVE_CLIENT_ID?.trim();
  const validUuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(bundledClientId ?? "");
  const placeholder = !bundledClientId || /^(00000000-|11111111-|example|placeholder|test)/i.test(bundledClientId);
  if (!validUuid || placeholder) {
    throw new Error("release bundle requires a publisher-supplied MEGLE_BUNDLED_ONEDRIVE_CLIENT_ID UUID");
  }
}
const profile = release ? "release" : "debug";
const coreBuildArgs = ["build", ...(release ? ["--release"] : []), "-p", "megle-core"];
const targetRoot = process.env.CARGO_TARGET_DIR
  ? path.resolve(root, process.env.CARGO_TARGET_DIR)
  : path.join(root, "target");
const providers = [
  { package: "megle-fake-provider", pluginId: "com.megle.fake-sync", constant: "GENERATED_FAKE_PROVIDER_SHA256" },
  { package: "megle-onedrive-provider", pluginId: "com.megle.onedrive", constant: "GENERATED_ONEDRIVE_PROVIDER_SHA256" }
];
for (const provider of providers) {
  execFileSync("cargo", ["build", ...(release ? ["--release"] : []), "-p", provider.package], { cwd: root, stdio: "inherit", shell: process.platform === "win32" });
}
const generated = ["// Generated by tools/build/build-bundled-plugins.mjs."];
for (const provider of providers) {
  const binaryName = process.platform === "win32" ? `${provider.package}.exe` : provider.package;
  const source = path.join(targetRoot, profile, binaryName);
  const pluginRoot = path.join(targetRoot, profile, "bundled-plugins", provider.pluginId);
  const binary = path.join(pluginRoot, "bin", binaryName);
  mkdirSync(path.dirname(binary), { recursive: true });
  copyFileSync(source, binary);
  const sha256 = createHash("sha256").update(readFileSync(binary)).digest("hex");
  const template = readFileSync(path.join(root, "bundled-plugins", provider.pluginId, "plugin.template.json"), "utf8");
  writeFileSync(path.join(pluginRoot, "plugin.json"), template.replaceAll("__SHA256__", sha256));
  const values = sha256.match(/../g).map(v => `0x${v}`);
  const rows = [values.slice(0, 16), values.slice(16)].map(row => `    ${row.join(", ")},`).join("\n");
  generated.push(`pub const ${provider.constant}: [u8; 32] = [\n${rows}\n];`);
  console.log(`[bundled-plugin] ${pluginRoot} ${sha256}`);
}
const generatedTrustPath = path.join(root, "crates", "core", "src", "plugins", "runtime", "generated_trust.rs");
const generatedTrust = `${generated.join("\n")}\n`;
let existingGeneratedTrust = null;
try {
  existingGeneratedTrust = readFileSync(generatedTrustPath, "utf8");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}
if (existingGeneratedTrust !== generatedTrust) {
  writeFileSync(generatedTrustPath, generatedTrust);
}

if (release) {
  execFileSync("cargo", coreBuildArgs, { cwd: root, stdio: "inherit", shell: process.platform === "win32" });
  const coreBinary = path.join(targetRoot, profile, process.platform === "win32" ? "megle-core.exe" : "megle-core");
  const artifact = readFileSync(coreBinary);
  if (!artifact.includes(Buffer.from(process.env.MEGLE_BUNDLED_ONEDRIVE_CLIENT_ID.trim()))) {
    throw new Error("release Core artifact does not embed MEGLE_BUNDLED_ONEDRIVE_CLIENT_ID");
  }
  console.log(`[bundled-client-id-verified] ${coreBinary}`);
}

if (process.argv.includes("--verify-onedrive")) {
  const pluginRoot = path.join(targetRoot, profile, "bundled-plugins", "com.megle.onedrive");
  const manifest = JSON.parse(readFileSync(path.join(pluginRoot, "plugin.json"), "utf8"));
  const binaryName = process.platform === "win32" ? "megle-onedrive-provider.exe" : "megle-onedrive-provider";
  const binary = path.join(pluginRoot, "bin", binaryName);
  const actual = createHash("sha256").update(readFileSync(binary)).digest("hex");
  if (manifest.integrity.sha256 !== actual) {
    throw new Error("OneDrive bundled manifest hash does not match the packaged executable");
  }
  console.log(`[bundled-plugin-verified] ${binary} ${actual}`);
  if (process.platform === "win32" && !release) {
    execFileSync(
      "cargo",
      ["test", "-p", "megle-onedrive-provider", "--features", "graph-emulator", "--test", "process_conformance"],
      {
        cwd: root,
        stdio: "inherit",
        shell: true,
        env: { ...process.env, MEGLE_ONEDRIVE_TEST_EXECUTABLE: binary },
      },
    );
    console.log(`[bundled-plugin-launched] ${binary}`);
  }
}
