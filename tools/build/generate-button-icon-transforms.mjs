import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { pathToFileURL } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import sharp from "sharp";

const design = new URL("../../apps/web/src/design/", import.meta.url);
const viewSize = 256;
const lightButtons = new Set(["ChevronLeft", "ChevronRight"]);

// Resolve package artwork from the facade so aliases such as Search and
// MagnifyingGlass never need a second hand-maintained lookup table.
export async function buttonIconGlyphs() {
  const source = await readFile(new URL("icons.ts", design), "utf8");
  const imports = new Map();
  for (const [, symbol, alias, module] of source.matchAll(/import\s*\{\s*(\w+)\s+as\s+(\w+)\s*\}\s*from\s*"(@phosphor-icons\/react\/dist\/csr\/\w+)"/g)) {
    imports.set(alias, { symbol, module });
  }
  const glyphs = new Map();
  for (const [, alias, name] of source.matchAll(/\bappIcon\(\s*(\w+),\s*"(\w+)"/g)) {
    const entry = imports.get(alias);
    assert.ok(entry, `Missing Phosphor import for ${name} (${alias})`);
    const Glyph = (await import(entry.module))[entry.symbol];
    assert.ok(Glyph, `Missing Phosphor artwork for ${name}`);
    glyphs.set(name, Glyph);
  }
  assert.ok(glyphs.size > 0, "No app icons found");
  assert.equal(glyphs.size, [...source.matchAll(/export const \w+\s*=/g)].length, "Unrecognized icon export");
  return glyphs;
}

export function glyphPath(Glyph, weight) {
  const svg = renderToStaticMarkup(createElement(Glyph, { size: viewSize, weight }));
  // CSS replaces only d. Fail on artwork with extra children, a custom fill
  // rule, a stroke or a local transform that swapping d would lose.
  const match = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="256" height="256" fill="currentColor" viewBox="0 0 256 256"><path d="([Mm][A-Za-z0-9.,+\s-]+)"><\/path><\/svg>$/.exec(svg);
  assert.ok(match, `Unsupported Phosphor SVG for ${Glyph.displayName} (${weight})`);
  return match[1];
}

// Measure painted edges in the Phosphor viewBox's own coordinate system.
// Half-coverage rejects near-transparent antialiasing fringes. Sampling at
// 1024px gives a 0.02 CSS px step at the target 20px button icon size.
export async function inkBounds(d, samples, transform) {
  const svg = createElement("svg", {
    xmlns: "http://www.w3.org/2000/svg",
    width: samples, height: samples, viewBox: "0 0 256 256",
  }, createElement("path", { d, transform }));
  const { data, info } = await sharp(Buffer.from(renderToStaticMarkup(svg)))
    .extractChannel("alpha").raw().toBuffer({ resolveWithObject: true });
  let left = info.width, top = info.height, right = 0, bottom = 0;
  for (let y = 0; y < info.height; y++) {
    const row = data.subarray(y * info.width, (y + 1) * info.width);
    const first = row.findIndex(alpha => alpha >= 128);
    if (first < 0) continue;
    left = Math.min(left, first);
    top = Math.min(top, y);
    right = Math.max(right, row.findLastIndex(alpha => alpha >= 128) + 1);
    bottom = y + 1;
  }
  assert.ok(right > left && bottom > top, "Expected visible Phosphor artwork");
  return [left, top, right, bottom].map(edge => edge * viewSize / samples);
}

function fitBold(bold, target) {
  const sx = (target[2] - target[0]) / (bold[2] - bold[0]);
  const sy = (target[3] - target[1]) / (bold[3] - bold[1]);
  const tx = target[0] - sx * bold[0];
  const ty = target[1] - sy * bold[1];
  const matrix = [sx, 0, 0, sy, tx, ty].map(n => Number(n.toFixed(5)));
  return `matrix(${matrix.join(", ")})`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const glyphs = await buttonIconGlyphs();
  const aliases = new Map();
  for (const name of [...glyphs.keys()].sort()) {
    const Glyph = glyphs.get(name);
    if (!aliases.has(Glyph)) aliases.set(Glyph, []);
    aliases.get(Glyph).push(name);
  }
  const license = await readFile(new URL("LICENSE", import.meta.resolve("@phosphor-icons/react/package.json")), "utf8");
  const lines = [
    `/* Generated by node tools/build/${basename(process.argv[1])}.`,
    " * Use the original bold path and fit it to the icon's previous painted edges. */",
    "/*! Phosphor Icons artwork",
    license.trim().replace(/\r\n/g, "\n"),
    "*/",
  ];
  for (const [Glyph, names] of aliases) {
    const boldPath = glyphPath(Glyph, "bold");
    const bold = await inkBounds(boldPath, 1024);
    const regular = await inkBounds(glyphPath(Glyph, "regular"), 1024);
    const selector = name => `[data-button-icon="${name}"]`;
    lines.push("", `${names.map(selector).join(",\n")} {`,
      `  --button-icon-path: path("${boldPath}");`,
      `  --button-icon-transform: ${fitBold(bold, regular)};`, "}");
    const light = names.filter(name => lightButtons.has(name));
    if (light.length) {
      const target = await inkBounds(glyphPath(Glyph, "light"), 1024);
      lines.push("", `${light.map(name => selector(name) + '[data-icon-weight="light"]').join(",\n")} {`,
        `  --button-icon-transform: ${fitBold(bold, target)};`, "}");
    }
  }
  await writeFile(new URL("buttonIconArtwork.css", design), lines.join("\n") + "\n");
  console.log(`Calibrated ${aliases.size} Phosphor glyphs for ${glyphs.size} app icons.`);
}
